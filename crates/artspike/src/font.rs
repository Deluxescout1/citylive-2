//! A tiny 3×5 bitmap font for labels on the compare sheet.

use render::{Framebuffer, palette::Color};

#[rustfmt::skip]
fn glyph(ch: char) -> [u8; 5] {
    // 3 bits per row, top row first, bit 2 = left column.
    match ch {
        'A' => [0b010, 0b101, 0b111, 0b101, 0b101],
        'B' => [0b110, 0b101, 0b110, 0b101, 0b110],
        'C' => [0b011, 0b100, 0b100, 0b100, 0b011],
        'D' => [0b110, 0b101, 0b101, 0b101, 0b110],
        'E' => [0b111, 0b100, 0b110, 0b100, 0b111],
        'F' => [0b111, 0b100, 0b110, 0b100, 0b100],
        'G' => [0b011, 0b100, 0b101, 0b101, 0b011],
        'H' => [0b101, 0b101, 0b111, 0b101, 0b101],
        'I' => [0b111, 0b010, 0b010, 0b010, 0b111],
        'J' => [0b011, 0b001, 0b001, 0b101, 0b010],
        'K' => [0b101, 0b101, 0b110, 0b101, 0b101],
        'L' => [0b100, 0b100, 0b100, 0b100, 0b111],
        'M' => [0b101, 0b111, 0b111, 0b101, 0b101],
        'N' => [0b101, 0b111, 0b111, 0b111, 0b101],
        'O' => [0b010, 0b101, 0b101, 0b101, 0b010],
        'P' => [0b110, 0b101, 0b110, 0b100, 0b100],
        'Q' => [0b010, 0b101, 0b101, 0b111, 0b011],
        'R' => [0b110, 0b101, 0b110, 0b101, 0b101],
        'S' => [0b011, 0b100, 0b010, 0b001, 0b110],
        'T' => [0b111, 0b010, 0b010, 0b010, 0b010],
        'U' => [0b101, 0b101, 0b101, 0b101, 0b111],
        'V' => [0b101, 0b101, 0b101, 0b101, 0b010],
        'W' => [0b101, 0b101, 0b111, 0b111, 0b101],
        'X' => [0b101, 0b101, 0b010, 0b101, 0b101],
        'Y' => [0b101, 0b101, 0b010, 0b010, 0b010],
        'Z' => [0b111, 0b001, 0b010, 0b100, 0b111],
        '0' => [0b111, 0b101, 0b101, 0b101, 0b111],
        '1' => [0b010, 0b110, 0b010, 0b010, 0b111],
        '2' => [0b111, 0b001, 0b111, 0b100, 0b111],
        '3' => [0b111, 0b001, 0b111, 0b001, 0b111],
        '4' => [0b101, 0b101, 0b111, 0b001, 0b001],
        '5' => [0b111, 0b100, 0b111, 0b001, 0b111],
        '6' => [0b111, 0b100, 0b111, 0b101, 0b111],
        '7' => [0b111, 0b001, 0b010, 0b010, 0b010],
        '8' => [0b111, 0b101, 0b111, 0b101, 0b111],
        '9' => [0b111, 0b101, 0b111, 0b001, 0b111],
        '-' => [0b000, 0b000, 0b111, 0b000, 0b000],
        '.' => [0b000, 0b000, 0b000, 0b000, 0b010],
        ':' => [0b000, 0b010, 0b000, 0b010, 0b000],
        '/' => [0b001, 0b001, 0b010, 0b100, 0b100],
        '%' => [0b101, 0b001, 0b010, 0b100, 0b101],
        '\''=> [0b010, 0b010, 0b000, 0b000, 0b000],
        _ => [0b000, 0b000, 0b000, 0b000, 0b000],
    }
}

/// Draw `text` at (x, y), one pixel per bit, `scale`× big.
pub fn text(fb: &mut Framebuffer, x: i32, y: i32, s: &str, c: Color, scale: i32) {
    let mut cx = x;
    for ch in s.chars() {
        if ch == ' ' {
            cx += 4 * scale;
            continue;
        }
        let g = glyph(ch.to_ascii_uppercase());
        for (row, bits) in g.iter().enumerate() {
            for col in 0..3 {
                if bits & (0b100 >> col) != 0 {
                    for dy in 0..scale {
                        for dx in 0..scale {
                            fb.put(cx + col as i32 * scale + dx, y + row as i32 * scale + dy, c);
                        }
                    }
                }
            }
        }
        cx += 4 * scale;
    }
}

/// Pixel width of a string at `scale`.
pub fn text_w(s: &str, scale: i32) -> i32 {
    s.chars().count() as i32 * 4 * scale - scale
}

/// Text following a diagonal band: `rise_per_px` shifts each pixel column's
/// baseline (positive = sloping down to the right, iso ~0.5 per +x face).
pub fn text_slope(fb: &mut Framebuffer, x: i32, y: i32, s: &str, c: Color, scale: i32, rise_per_px: i32) {
    let mut cx = x;
    for ch in s.chars() {
        if ch == ' ' {
            cx += 4 * scale;
            continue;
        }
        let g = glyph(ch.to_ascii_uppercase());
        let yoff = (cx - x) * rise_per_px / 2; // rise per 2 px of x
        for (row, bits) in g.iter().enumerate() {
            for col in 0..3 {
                if bits & (0b100 >> col) != 0 {
                    for dy in 0..scale {
                        for dx in 0..scale {
                            let px = cx + col as i32 * scale + dx;
                            fb.put(px, y + yoff + row as i32 * scale + dy, c);
                        }
                    }
                }
            }
        }
        cx += 4 * scale;
    }
}
